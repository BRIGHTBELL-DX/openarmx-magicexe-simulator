/** 클립이 variants(마디 수별로 완전히 다른 안무)를 가지면 그 마디 목록,
 *  없으면 단일 clip.bars 하나짜리 목록. 사용자 피드백 반영 — "1마디를
 *  그냥 늘려서 2·3·4마디를 만들지 말고, 마디가 늘수록(시간이 남으면)
 *  1번 조인트를 더 쓰는 등 실제로 다른/더 발전된 동작이 되게" 하기 위해
 *  마디별로 keys를 통째로 따로 정의할 수 있게 한 구조. */
function _clipBarOptions(c) {
  if (c.variants) return Object.keys(c.variants).map(Number).sort((a, b) => a - b);
  return [Math.max(1, c.bars || 1)];
}

/** 요청한 마디 수에 맞는 keys와 실제 적용된 마디 수를 반환.
 *  variants면 정확히 일치하는 마디를 찾고, 없으면 그보다 작은 것 중 가장
 *  큰 값(내림) — 예: 3마디를 요청했는데 1·2·4마디만 있으면 2마디 사용. */
function _clipKeysForBars(c, wantBars) {
  if (c.variants) {
    const options = _clipBarOptions(c);
    const want = wantBars || options[0];
    const pick = options.filter(b => b <= want).pop() ?? options[0];
    return { bars: pick, keys: c.variants[pick].keys };
  }
  return { bars: Math.max(1, c.bars || 1), keys: c.keys };
}

