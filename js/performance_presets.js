/** 클립의 실제 길이(마디) — 단일 구간(keys)만 지원하는 v0 버전.
 *  phases(다단계)는 클립 라이브러리가 커지면 나중에 추가한다. */
function _clipBars(c) {
  return Math.max(1, c.bars || 1);
}

